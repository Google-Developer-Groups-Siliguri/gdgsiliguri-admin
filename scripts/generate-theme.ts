import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import {
  argbFromHex,
  Hct,
  hexFromArgb,
  SchemeTonalSpot,
  type DynamicScheme,
} from "@material/material-color-utilities";

const SEED = "#4285F4";
const OUTPUT = fileURLToPath(new URL("../src/app/theme.css", import.meta.url));

const ROLES = [
  "primary",
  "onPrimary",
  "primaryContainer",
  "onPrimaryContainer",
  "primaryFixed",
  "primaryFixedDim",
  "onPrimaryFixed",
  "onPrimaryFixedVariant",
  "secondary",
  "onSecondary",
  "secondaryContainer",
  "onSecondaryContainer",
  "tertiary",
  "onTertiary",
  "tertiaryContainer",
  "onTertiaryContainer",
  "error",
  "onError",
  "errorContainer",
  "onErrorContainer",
  "background",
  "onBackground",
  "surface",
  "surfaceDim",
  "surfaceBright",
  "surfaceContainerLowest",
  "surfaceContainerLow",
  "surfaceContainer",
  "surfaceContainerHigh",
  "surfaceContainerHighest",
  "onSurface",
  "surfaceVariant",
  "onSurfaceVariant",
  "surfaceTint",
  "outline",
  "outlineVariant",
  "inverseSurface",
  "inverseOnSurface",
  "inversePrimary",
  "scrim",
  "shadow",
] as const satisfies readonly (keyof DynamicScheme)[];

function kebab(role: string): string {
  return role.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}

function declarations(isDark: boolean, indent: string): string {
  const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(SEED)), isDark, 0);
  return ROLES.map(
    (role) => `${indent}--md-sys-color-${kebab(role)}: ${hexFromArgb(scheme[role] as number)};`,
  ).join("\n");
}

const themeMappings = ROLES.map(
  (role) => `  --color-${kebab(role)}: var(--md-sys-color-${kebab(role)});`,
).join("\n");

const css = `/* Generated by scripts/generate-theme.ts from seed ${SEED} (Tonal Spot). Do not edit. */

:root,
[data-theme="light"] {
  color-scheme: light;
${declarations(false, "  ")}
}

[data-theme="dark"] {
  color-scheme: dark;
${declarations(true, "  ")}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${declarations(true, "    ")}
  }
}

@theme inline {
${themeMappings}
}
`;

writeFileSync(OUTPUT, css);
console.log(`Wrote ${OUTPUT}`);
